interface FunctionMatcher {
  exact: Set<string>;
  prefixes: string[];
}

function compileMatcher(patterns: readonly string[]): FunctionMatcher {
  const exact = new Set<string>();
  const prefixes: string[] = [];
  for (const p of patterns) {
    const upper = p.trim().toUpperCase();
    if (!upper) continue;
    if (upper.endsWith('*')) prefixes.push(upper.slice(0, -1));
    else exact.add(upper);
  }
  return { exact, prefixes };
}

function matches(m: FunctionMatcher, name: string): boolean {
  if (m.exact.has(name)) return true;
  for (const p of m.prefixes) if (name.startsWith(p)) return true;
  return false;
}

const DEFAULT_MATCHER = compileMatcher(DEFAULT_BLOCKED_FUNCTIONS);
// Config arrays are usually the same object on every call, so compiled matchers are cached by identity.
const matcherCache = new WeakMap<readonly string[], FunctionMatcher>();

function matcherFor(list: readonly string[]): FunctionMatcher {
  let m = matcherCache.get(list);
  if (!m) {
    m = compileMatcher(list);
    matcherCache.set(list, m);
  }
  return m;
}

/**
 * Whether calling the function `name` should be blocked.
 *
 * Matching is case-insensitive and a trailing `*` in a pattern matches a prefix.
 * A schema-qualified name (`pg_catalog.pg_sleep`) is blocked when any part
 * matches. `extraBlocked` is checked first and always wins; `allowed` (matched
 * against the full name or its last part) only overrides DEFAULT_BLOCKED_FUNCTIONS.
 *
 * @param name - Function name as written, optionally schema-qualified
 * @param extraBlocked - Additional names or patterns to block
 * @param allowed - Names or patterns to allow even though the default list blocks them
 */
export function isBlockedFunction(name: string, extraBlocked?: string[], allowed?: string[]): boolean {
  const full = name.trim().toUpperCase();
  if (!full) return false;
  const parts = full.indexOf('.') >= 0 ? full.split('.') : null;
  const last = parts ? parts[parts.length - 1] : full;

  const anyPart = (m: FunctionMatcher): boolean => {
    if (matches(m, full)) return true;
    if (parts) for (const p of parts) if (p && matches(m, p)) return true;
    return false;
  };

  if (extraBlocked && extraBlocked.length > 0 && anyPart(matcherFor(extraBlocked))) return true;
  if (allowed && allowed.length > 0) {
    const m = matcherFor(allowed);
    if (matches(m, full) || matches(m, last)) return false;
  }
  return anyPart(DEFAULT_MATCHER);
}
