/**
 * Words reserved in at least one supported dialect (uppercase). An identifier
 * spelled like one of these should be quoted. Use `isReservedKeyword()` for a
 * single dialect.
 */
export const RESERVED_KEYWORDS: ReadonlySet<string> = new Set([
  ...RESERVED_POSTGRES,
  ...RESERVED_MYSQL,
  ...RESERVED_SQLITE,
  ...RESERVED_MSSQL,
]);

/**
 * Whether `word` is reserved in `dialect` (case-insensitive). For `generic`
 * (or no dialect) the union of all dialects is used.
 */
export function isReservedKeyword(word: string, dialect: SqlDialect = 'generic'): boolean {
  const upper = word.toUpperCase();
  if (dialect === 'generic') return RESERVED_KEYWORDS.has(upper);
  return RESERVED_BY_DIALECT[dialect].has(upper);
}

